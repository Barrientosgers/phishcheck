/**
 * Edit distance: the fewest single-character insertions, deletions or substitutions needed
 * to turn `a` into `b`. `northwlnd` is 1 edit from `northwind`, which is how we spot lookalikes.
 * Classic dynamic programming, keeping only two rows of the table in memory.
 */
export function levenshtein(a: string, b: string): number {
  if (a === b) return 0
  if (a.length === 0) return b.length
  if (b.length === 0) return a.length

  let previous = Array.from({ length: b.length + 1 }, (_, j) => j)
  for (let i = 1; i <= a.length; i++) {
    const current = [i]
    for (let j = 1; j <= b.length; j++) {
      const cost = a[i - 1] === b[j - 1] ? 0 : 1
      current[j] = Math.min(previous[j] + 1, current[j - 1] + 1, previous[j - 1] + cost)
    }
    previous = current
  }
  return previous[b.length]
}
